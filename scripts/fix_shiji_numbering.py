"""修正史记章节编号：中文数字→阿拉伯数字"""
import re, pathlib

SHIJI_DIR = pathlib.Path("data/raw/shiji")

CN_NUMS = {
    '一':1,'二':2,'三':3,'四':4,'五':5,'六':6,'七':7,'八':8,'九':9,'十':10,
    '十一':11,'十二':12,'十三':13,'十四':14,'十五':15,'十六':16,'十七':17,
    '十八':18,'十九':19,'二十':20,'二十一':21,'二十二':22,'二十三':23,
    '二十四':24,'二十五':25,'二十六':26,'二十七':27,'二十八':28,'二十九':29,
    '三十':30,'三十一':31,'三十二':32,'三十三':33,'三十四':34,'三十五':35,
    '三十六':36,'三十七':37,'三十八':38,'三十九':39,'四十':40,'四十一':41,
    '四十二':42,'四十三':43,'四十四':44,'四十五':45,'四十六':46,'四十七':47,
    '四十八':48,'四十九':49,'五十':50,'五十一':51,'五十二':52,'五十三':53,
    '五十四':54,'五十五':55,'五十六':56,'五十七':57,'五十八':58,'五十九':59,
    '六十':60,'六十一':61,'六十二':62,'六十三':63,'六十四':64,'六十五':65,
    '六十六':66,'六十七':67,'六十八':68,'六十九':69,'七十':70,
}

renamed = 0
for f in SHIJI_DIR.glob("卷000_*.md"):
    # Extract Chinese numeral from title
    m = re.match(r'卷000_(.+?)第([一二三四五六七八九十百千]+)', f.name)
    if m:
        title_part = m.group(1)
        cn_num = m.group(2)
        num = CN_NUMS.get(cn_num, 0)
        if num > 0:
            new_name = f"卷{num:03d}_{title_part}第{cn_num}.md"
            f.rename(SHIJI_DIR / new_name)
            renamed += 1

print(f"renamed {renamed} files")
# Show sample
for f in sorted(SHIJI_DIR.glob("*.md"))[:5]:
    print(f"  {f.name}")
